// Build COMPONENTS.md: a catalog of every exported component, read from the
// @ployComponent JSDoc tags, with its import line and Storybook link. It ships
// in the package so an agent working in a consuming site can find components
// without opening each file.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve, sep } from "node:path";

const STORYBOOK_URL = "https://xnsengo.github.io/poly-storybook-demp/";
const PKG = "@xnsengo/investia-ui";

const root = resolve(import.meta.dirname, "..");
const componentsDir = join(root, "src", "components");

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const files = walk(componentsDir);
const toPosix = (path) => path.split(sep).join("/");

// Storybook ids follow the sanitised title, e.g. "Atoms/Form controls" -> atoms-form-controls.
const storyId = (title) =>
  title
    .toLowerCase()
    .replace(/[^a-z0-9-]/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");

// Map each component file to the story title that imports it.
const storyTitleFor = new Map();
for (const file of files.filter((f) => f.endsWith(".stories.tsx"))) {
  const source = readFileSync(file, "utf8");
  const title = source.match(/title:\s*"([^"]+)"/)?.[1];
  if (!title) continue;
  for (const [, spec] of source.matchAll(/from "(\.\/[^"]+|\.\.\/[^"]+)"/g)) {
    const target = toPosix(relative(root, resolve(file, "..", spec)));
    if (!storyTitleFor.has(target)) storyTitleFor.set(target, title);
  }
}

const LAYERS = ["atoms", "molecules", "organisms", "templates", "pages"];
const entries = [];
for (const file of files) {
  if (!/\.tsx?$/.test(file) || file.endsWith(".stories.tsx")) continue;
  const rel = toPosix(relative(root, file));
  if (rel.includes("/design-system/")) continue;
  const source = readFileSync(file, "utf8");
  const pattern = /\/\*\*([\s\S]*?)\*\/\s*export (?:function|const) (\w+)/g;
  for (const [, doc, name] of source.matchAll(pattern)) {
    if (!doc.includes("@ployComponent")) continue;
    const tag = (key) =>
      doc.match(new RegExp(`@${key}\\s+([^\\n]*)`))?.[1].replace(/\s*\*?\s*$/, "").trim();
    const layer = rel.split("/")[2];
    const group = layer === "organisms" ? rel.split("/")[3] : "";
    const title = storyTitleFor.get(rel.replace(/\.tsx?$/, ""));
    entries.push({
      name,
      layer,
      group,
      file: rel,
      type: tag("ployComponentType"),
      tags: tag("ployComponentTags"),
      description: tag("ployComponentDescription") ?? "",
      story: title ? `${STORYBOOK_URL}?path=/docs/${storyId(title)}--docs` : "",
    });
  }
}

const order = (e) => LAYERS.indexOf(e.layer) * 100 + (e.group ? 1 : 0);
entries.sort((a, b) => order(a) - order(b) || a.group.localeCompare(b.group) || a.file.localeCompare(b.file));

const lines = [
  `# ${PKG} component catalog`,
  "",
  "Generated by `npm run build:catalog` from the `@ployComponent` JSDoc tags. Do not edit by hand.",
  "",
  `Live Storybook (props, variants, EN/FR examples): ${STORYBOOK_URL}`,
  "",
  "Every name below is a named export of the package root:",
  "",
  "```tsx",
  `import { Button, SiteShell, Body2Products } from "${PKG}";`,
  "```",
  "",
];
let heading = "";
for (const entry of entries) {
  const current = entry.group ? `${entry.layer} / ${entry.group}` : entry.layer;
  if (current !== heading) {
    heading = current;
    lines.push(`## ${current.replace(/^./, (c) => c.toUpperCase())}`, "");
  }
  lines.push(`### \`${entry.name}\``, "");
  if (entry.description) lines.push(entry.description, "");
  const meta = [
    entry.type && `type: ${entry.type}`,
    entry.tags && `tags: ${entry.tags}`,
    `source: \`${entry.file}\``,
    entry.story && `[Storybook](${entry.story})`,
  ].filter(Boolean);
  lines.push(meta.join(" · "), "");
}

writeFileSync(join(root, "COMPONENTS.md"), lines.join("\n"));
console.log(`COMPONENTS.md: ${entries.length} components`);
